    /** 错误码是否在表里登记过 */
    public static function exists($code)
    {
        return isset(self::$codes[(string) $code]);
    }

    /** [内部说明, 用户文案] */
    public static function describe($code)
    {
        $code = (string) $code;
        if (!isset(self::$codes[$code])) {
            return ['未登记的错误码:' . $code, self::$codes['9999'][1]];
        }
        return self::$codes[$code];
    }

    /** 用户文案，表里没有就返回兜底 */
    public static function msg($code, $fallback = null)
    {
        if ($fallback !== null && $fallback !== '') {
            return $fallback;
        }
        return self::describe($code)[1];
    }
